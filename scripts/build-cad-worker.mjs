// Bundles src/lib/cad/detect-worker.ts and the modules it imports into one classic
// worker script, public/cad-detect-worker.js (gitignored, rebuilt by `prebuild` and
// build-mobile). The AutoCAD PDF editor runs SHX detection in it.
//
// Why not `new Worker(new URL(...))`? Turbopack (Next 16.0) copies the .ts file as a
// plain asset instead of compiling it. This tiny bundler only needs to handle the
// cad modules: relative `import { a, b } from './x.ts'` and `export function/const`.
// Anything else fails the build loudly rather than shipping a broken worker.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const CAD = path.join(root, 'src/lib/cad')
const ENTRY = 'detect-worker'

function transpile(name) {
    const src = fs.readFileSync(path.join(CAD, `${name}.ts`), 'utf8')
    return ts.transpileModule(src, {
        fileName: `${name}.ts`,
        compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: true, verbatimModuleSyntax: false },
    }).outputText
}

/** Returns the bundle source. Modules are wrapped in their own scope, dependencies first. */
export function bundleCadWorker() {
    const order = []
    const seen = new Set()
    const code = new Map()
    const visit = (name, stack = []) => {
        if (seen.has(name)) return
        if (stack.includes(name)) throw new Error(`cad worker: import cycle ${[...stack, name].join(' → ')}`)
        const js = transpile(name)
        const deps = []
        const exports = []
        const lines = js.split(/\r?\n/).map((line) => {
            let m
            if ((m = /^import\s*\{([^}]*)\}\s*from\s*['"]\.\/([\w-]+)\.ts['"];?\s*$/.exec(line))) {
                deps.push(m[2])
                const names = m[1]
                    .split(',')
                    .map((s) => s.trim())
                    .filter(Boolean)
                    .map((s) => s.replace(/^(\w+)\s+as\s+(\w+)$/, '$1: $2'))
                return `const { ${names.join(', ')} } = __m[${JSON.stringify(m[2])}];`
            }
            if ((m = /^export\s+(async\s+function\*?|function\*?|const|let|class)\s+(\w+)/.exec(line))) {
                exports.push(m[2])
                return line.replace(/^export\s+/, '')
            }
            if (/^\s*(import|export)\b/.test(line)) throw new Error(`cad worker: ${name}.ts has a statement this bundler can't handle: ${line}`)
            return line
        })
        for (const d of deps) visit(d, [...stack, name])
        seen.add(name)
        order.push(name)
        code.set(name, `__m[${JSON.stringify(name)}] = (() => {\n${lines.join('\n')}\nreturn { ${exports.join(', ')} };\n})();`)
    }
    visit(ENTRY)
    return [
        '// Generated by scripts/build-cad-worker.mjs from src/lib/cad/*.ts. Do not edit.',
        '"use strict";',
        '(() => {',
        'const __m = {};',
        ...order.map((n) => code.get(n)),
        // For the unit test, which loads this file in a VM and compares results.
        'self.__cad = __m;',
        '})();',
        '',
    ].join('\n')
}

export function buildCadWorker(out = path.join(root, 'public/cad-detect-worker.js')) {
    fs.mkdirSync(path.dirname(out), { recursive: true })
    fs.writeFileSync(out, bundleCadWorker())
    return out
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const out = buildCadWorker(process.argv[2])
    console.log(`cad worker → ${path.relative(root, out)}`)
}
